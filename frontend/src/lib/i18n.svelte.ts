const dictionaries = { de, en } as const;
export type Lang = keyof typeof dictionaries;
export const languages: Lang[] = ['de', 'en'];

function initialLang(): Lang {
	try {
		const stored = localStorage.getItem('eilkurier.lang');
		if (stored === 'de' || stored === 'en') return stored;
	} catch {
		/* storage unavailable */
	}
	return typeof navigator !== 'undefined' && navigator.language?.startsWith('en') ? 'en' : 'de';
}

export const i18n = $state({ lang: initialLang() });

export function setLang(lang: Lang): void {
	i18n.lang = lang;
	document.documentElement.lang = lang;
	try {
		localStorage.setItem('eilkurier.lang', lang);
	} catch {
		/* storage unavailable */
	}
}

export function t(key: MessageKey, params: Record<string, string | number> = {}): string {
	const template: string = dictionaries[i18n.lang][key] ?? de[key];
	return template.replace(/\{(\w+)\}/g, (_, name: string) => String(params[name] ?? `{${name}}`));
}

export function weekdays(style: 'short' | 'long' = 'short'): string[] {
	return t(style === 'short' ? 'days.short' : 'days.long').split(',');
}

export function formatDate(value: string | Date): string {
	const date = typeof value === 'string' ? new Date(value) : value;
	return date.toLocaleDateString(i18n.lang === 'de' ? 'de-DE' : 'en-GB', {
		day: '2-digit',
		month: '2-digit',
		year: 'numeric'
	});
}

export function formatDateTime(value: string): string {
	return new Date(value).toLocaleString(i18n.lang === 'de' ? 'de-DE' : 'en-GB', {
		dateStyle: 'short',
		timeStyle: 'short'
	});
}
